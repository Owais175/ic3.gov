            <h2> Privacy Policy — Cyber Rapid Action Unit (CRAU)</h2>
            <h3>1. Introduction</h3>
            <p>This Privacy Policy governs the operations of the Cyber Rapid Action Unit (CRAU),
                functioning under the
                Ministry of Home Affairs (MHA), in coordination with the Indian Cyber Crime
                Coordination
                Centre (I4C) and
                the Central Bureau of Investigation (CBI).
            </p>
            <p>CRAU respects the privacy of citizens, organizations, and institutions, and ensures that all data collected,
                analyzed, or processed during cybercrime investigations is handled with confidentiality, legality,
                and
                accountability.
            </p>
            <h3>2. Scope of Operation</h3>
            <p>CRAU does not engage in broad public data collection.
            </p>
            <p>Its operations are limited to cases formally assigned or escalated by authorized agencies
                such as MHA, I4C,
                or CBI.
            </p>
            <p>It handles only high-priority, complex, or large-scale cybercrime investigations, ensuring a
                selective and
                secure approach to data handling.
            </p>
            <h3>3. Nature of Data Collected
            </h3>
            <p>Data processed by CRAU may include:
            </p>
            <ul>
                <li>
                    <p>Digital forensic evidence and logs relevant to active cases.
                    </p>
                </li>
                <li>
                    <p>Communication metadata for investigation and tracing.
                    </p>
                </li>
                <li>
                    <p>Cyber threat indicators and network signatures.
                    </p>
                </li>
                <li>
                    <p>Operational records shared by central and state cyber enforcement units.
                    </p>
                </li>
            </ul>
            <p>CRAU does not store or process personal data unrelated to official investigations.
            </p>
            <h3>4. Purpose of Data Usage
            </h3>
            <p>The information collected or processed by CRAU is used strictly for:
            </p>
            <ul>
                <li>
                    <p>Investigating and mitigating major cyber threats.</p>
                </li>
                <li>
                    <p>Supporting coordinated enforcement with MHA, I4C, CBI, and CERT-In.</p>
                </li>
                <li>
                    <p>Preserving digital evidence for lawful prosecution.</p>
                </li>
                <li>
                    <p>Conducting post-incident reviews and preventive policy development.</p>
                </li>
            </ul>
            <p>No data is shared outside authorized government channels.
            </p>
            <h3>5. Data Security and Retention
            </h3>
            <p>CRAU employs robust security protocols including:
            </p>
            <ul>
                <li>
                    <p>End-to-end encryption for all transmitted data.
                    </p>
                </li>
                <li>
                    <p>Restricted access control with role-based permissions. </p>
                </li>
                <li>
                    <p>Multi-factor authentication for authorized personnel.
                    </p>
                </li>
                <li>
                    <p>Tamper-proof audit trails for every data access instance.
                    </p>
                </li>
            </ul>
            <p>All data is stored within secure Government of India data centers and retained only as per
                the directives of
                MHA and I4C.</p>
            <h3>6. Data Confidentiality and Oversight</h3>
            <p>Access to sensitive information is governed by strict internal policies.
                Only authorized officers deputed from MHA, I4C, or CBI may review, process, or disseminate case-related
                information.
            </p>
            <p>Every operation is subject to oversight, auditing, and accountability mechanisms ensuring
                compliance with
                national cybersecurity and privacy frameworks.
            </p>
            <h3>7. Third-Party Access
            </h3>
            <p>No external or private entity is permitted to access CRAU systems, databases, or intelligence reports.
            </p>
            <p>All information sharing is done exclusively with government agencies on a need-to-know basis.
            </p>
            <h3>8. Transparency and Legal Compliance
            </h3>
            <p>CRAU operates within the framework of the Information Technology Act, 2000, and the
                associated rules,
                directives, and advisories issued by the Government of India.
            </p>
            <p>All actions are undertaken with full adherence to national data privacy and information security laws.
            </p>
